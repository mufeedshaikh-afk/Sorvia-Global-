import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { buildSync } = createRequire(require.resolve('vite/package.json'))('esbuild');
const output = buildSync({ entryPoints: ['src/accountValidation.ts'], bundle: true, write: false, format: 'cjs', platform: 'node' });
const compiled = { exports: {} };
new Function('module', 'exports', 'require', output.outputFiles[0].text)(compiled, compiled.exports, require);
const { validateAuth, isEmail } = compiled.exports;
const draft = { name: 'Alex Sample', email: 'alex@example.com', password: 'preview-only-123', confirm: 'preview-only-123' };
assert.deepEqual(validateAuth('signin', draft), {});
assert.deepEqual(validateAuth('register', draft), {});
assert.deepEqual(validateAuth('reset', { ...draft, name: '', password: '', confirm: '' }), {});
assert.ok(validateAuth('register', { ...draft, name: '   ' }).name);
assert.ok(validateAuth('signin', { ...draft, email: 'bad' }).email);
assert.ok(validateAuth('signin', { ...draft, password: 'short' }).password);
assert.ok(validateAuth('signin', { ...draft, password: '        ' }).password);
assert.ok(validateAuth('register', { ...draft, confirm: 'different' }).confirm);
assert.equal(isEmail('  alex@example.com  '), true);
assert.equal(isEmail('alex @example.com'), false);
console.log('10 account form validation assertions passed.');
