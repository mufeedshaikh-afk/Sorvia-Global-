import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { buildSync } = createRequire(require.resolve('vite/package.json'))('esbuild');
const output = buildSync({ entryPoints: ['src/supportData.ts'], bundle: true, write: false, format: 'cjs', platform: 'node' });
const compiled = { exports: {} };
new Function('module', 'exports', 'require', output.outputFiles[0].text)(compiled, compiled.exports, require);
const { validateEnquiry, validateTracking, findTrackingExample, policies, faqs } = compiled.exports;
const enquiry = { name: 'Alex Sample', email: 'alex@example.com', topic: 'Product information', order: '', message: 'A fictional product question for preview.' };
assert.deepEqual(validateEnquiry(enquiry), {});
assert.equal(Object.keys(validateEnquiry({ name: '', email: '', topic: '', order: '', message: '' })).length, 4);
assert.ok(validateEnquiry({ ...enquiry, name: '  ' }).name);
assert.ok(validateEnquiry({ ...enquiry, email: 'bad' }).email);
assert.ok(validateEnquiry({ ...enquiry, topic: 'invalid' }).topic);
assert.ok(validateEnquiry({ ...enquiry, message: 'short' }).message);
assert.ok(validateEnquiry({ ...enquiry, message: 'a'.repeat(2001) }).message);
assert.deepEqual(validateTracking('DEMO-1001', 'alex@example.com'), {});
assert.equal(Object.keys(validateTracking('', '')).length, 2);
assert.equal(findTrackingExample(' demo-1001 ', ' ALEX@example.com ').status, 'Processing');
assert.equal(findTrackingExample('DEMO-1002', 'alex@example.com').stage, 4);
assert.equal(findTrackingExample('DEMO-1001', 'other@example.com'), undefined);
assert.equal(findTrackingExample('UNKNOWN', 'alex@example.com'), undefined);
assert.equal(new Set(policies.map(p => p.path)).size, 4);
assert.equal(faqs.length, 8);
console.log('15 support/tracking validation assertions passed.');
