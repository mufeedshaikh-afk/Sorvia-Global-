import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { buildSync } = createRequire(require.resolve('vite/package.json'))('esbuild');
const output = buildSync({ entryPoints: ['src/adminData.ts'], bundle: true, write: false, format: 'cjs', platform: 'node' });
const compiled = { exports: {} };
new Function('module', 'exports', 'require', output.outputFiles[0].text)(compiled, compiled.exports, require);
const { createAdminSamples, validateAdminProduct, imageFileError, validateAdminAccess } = compiled.exports;
const catalog = createAdminSamples();
const draft = { ...catalog[0], id: 'NEW', sku: 'DEMO-NEW' };
assert.equal(catalog.length, 30);
assert.ok(catalog.every(p => Object.keys(validateAdminProduct(p, catalog)).length === 0));
assert.deepEqual(validateAdminProduct(draft, catalog), {});
assert.ok(validateAdminProduct({ ...draft, sku: ' sample-01 ' }, catalog).sku);
assert.deepEqual(validateAdminProduct(catalog[0], catalog), {});
assert.ok(validateAdminProduct({ ...draft, sku: 'bad sku!' }, catalog).sku);
assert.ok(validateAdminProduct({ ...draft, name: '   ' }, catalog).name);
assert.ok(validateAdminProduct({ ...draft, category: 'unknown' }, catalog).category);
assert.ok(validateAdminProduct({ ...draft, material: 'unknown' }, catalog).material);
assert.ok(validateAdminProduct({ ...draft, description: '' }, catalog).description);
assert.ok(validateAdminProduct({ ...draft, price: '-1' }, catalog).price);
assert.ok(validateAdminProduct({ ...draft, price: '1.234' }, catalog).price);
assert.ok(validateAdminProduct({ ...draft, price: '1e3' }, catalog).price);
assert.equal(validateAdminProduct({ ...draft, price: '0.00' }, catalog).price, undefined);
assert.ok(validateAdminProduct({ ...draft, currency: 'BTC' }, catalog).currency);
assert.ok(validateAdminProduct({ ...draft, availability: 'unknown' }, catalog).availability);
assert.ok(validateAdminProduct({ ...draft, imageUrl: '' }, catalog).imageUrl);
assert.ok(validateAdminProduct({ ...draft, imageAlt: '' }, catalog).imageAlt);
assert.ok(validateAdminProduct({ ...draft, collectionPaths: ['/bad'] }, catalog).collectionPaths);
assert.equal(imageFileError({ type: 'image/jpeg', size: 100 }), '');
assert.ok(imageFileError({ type: 'image/svg+xml', size: 100 }));
assert.ok(imageFileError({ type: 'image/png', size: 5 * 1024 * 1024 + 1 }));
assert.ok(imageFileError({ type: 'image/webp', size: 0 }));
assert.deepEqual(validateAdminAccess('alex@example.com', 'preview-only-123'), { email: '', password: '' });
assert.ok(validateAdminAccess('bad', 'preview-only-123').email);
assert.ok(validateAdminAccess('alex@example.com', 'short').password);
catalog[0].name = 'Changed demo';
assert.notEqual(createAdminSamples()[0].name, 'Changed demo');
console.log('27 admin validation assertions passed.');
